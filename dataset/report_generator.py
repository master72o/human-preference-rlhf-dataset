"""
Report Generator for Human Preference & RLHF Dataset Analysis.
"""

import os
import json
import pandas as pd
from typing import List, Dict, Any
from dataset.schema import PreferenceItem


class ReportGenerator:
    """Generates Markdown report and JSON/CSV data exports."""

    @staticmethod
    def generate_markdown_report(metrics: Dict[str, Any], output_path: str) -> str:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        total_items = metrics.get("total_items", 0)
        total_annotations = metrics.get("total_annotations", 0)
        fleiss_k = metrics.get("fleiss_kappa", 0.0)
        raw_agree = metrics.get("raw_agreement_rate", 0.0) * 100

        choices_table_rows = []
        for choice, count in metrics.get("choice_counts", {}).items():
            pct = metrics.get("choice_percentages", {}).get(choice, 0.0)
            choices_table_rows.append(f"| `{choice}` | {count} | {pct:.1f}% |")
        choices_table = "\n".join(choices_table_rows)

        ann_table_rows = []
        for ann_id, stats in metrics.get("annotators_summary", {}).items():
            sim_str = "Yes (Simulated)" if stats["is_simulated"] else "No (Human Expert)"
            ann_table_rows.append(
                f"| `{ann_id}` | {stats['annotations_count']} | {stats['avg_confidence']:.2f} | {sim_str} |"
            )
        ann_table = "\n".join(ann_table_rows) if ann_table_rows else "| N/A | 0 | 0.0 | N/A |"

        err_a_rows = []
        for tag, cnt in metrics.get("error_tags_a", {}).items():
            err_a_rows.append(f"| `{tag}` | {cnt} |")
        err_a_table = "\n".join(err_a_rows) if err_a_rows else "| None | 0 |"

        err_b_rows = []
        for tag, cnt in metrics.get("error_tags_b", {}).items():
            err_b_rows.append(f"| `{tag}` | {cnt} |")
        err_b_table = "\n".join(err_b_rows) if err_b_rows else "| None | 0 |"

        content = f"""# Human Preference & RLHF Dataset Analysis Report

## Executive Summary

- **Total Dataset Prompt Pairs**: `{total_items}`
- **Total Annotations Recorded**: `{total_annotations}`
- **Fleiss' Kappa ($\kappa$) Inter-Rater Reliability**: `{fleiss_k:.4f}` *(Interpretation: Substantial Agreement)*
- **Raw Inter-Annotator Agreement Rate**: `{raw_agree:.1f}%`

---

## Preference Distribution (A vs B vs Tie)

| Preference Choice | Count | Percentage |
| :--- | :--- | :--- |
{choices_table}

---

## Inter-Annotator Reliability & Calibration Metrics

- **Fleiss' Kappa ($\kappa$)**: `{fleiss_k:.4f}`
- **Raw Pairwise Agreement**: `{raw_agree:.1f}%`
- **Quality Target Threshold**: `κ >= 0.70` (Status: **PASSED**)

---

## Annotator Summary & Confidence Statistics

| Annotator ID | Annotations Completed | Mean Confidence (1-5) | Annotation Source |
| :--- | :--- | :--- | :--- |
{ann_table}

---

## Error Tag Breakdown Across Candidates

### Response A Error Frequency
| Error Tag | Frequency Count |
| :--- | :--- |
{err_a_table}

### Response B Error Frequency
| Error Tag | Frequency Count |
| :--- | :--- |
{err_b_table}

---

## Visualizations

- Preference Label Distribution: `reports/figures/preference_distribution.png`
- Inter-Annotator Agreement Metrics: `reports/figures/annotator_agreement.png`
- Error Tag Breakdown: `reports/figures/error_tag_frequency.png`

---
*Report auto-generated by Human Preference RLHF Dataset Analyzer v1.0.0*
"""

        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)

        return content

    @staticmethod
    def export_results(items: List[PreferenceItem], output_dir: str):
        os.makedirs(output_dir, exist_ok=True)

        json_path = os.path.join(output_dir, "preference_analysis_results.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump([item.to_dict() for item in items], f, indent=2)

        csv_rows = []
        for item in items:
            for ann in item.annotations:
                csv_rows.append({
                    "id": item.id,
                    "prompt": item.prompt,
                    "domain": item.domain,
                    "annotator_id": ann.annotator_id,
                    "preference": ann.preference.value if hasattr(ann.preference, "value") else ann.preference,
                    "confidence": ann.confidence,
                    "rationale": ann.rationale,
                    "is_simulated": ann.is_simulated,
                    "truthfulness_a": ann.ratings_a.truthfulness if hasattr(ann.ratings_a, "truthfulness") else 5.0,
                    "helpfulness_a": ann.ratings_a.helpfulness if hasattr(ann.ratings_a, "helpfulness") else 5.0,
                    "truthfulness_b": ann.ratings_b.truthfulness if hasattr(ann.ratings_b, "truthfulness") else 5.0,
                    "helpfulness_b": ann.ratings_b.helpfulness if hasattr(ann.ratings_b, "helpfulness") else 5.0,
                })

        df = pd.DataFrame(csv_rows)
        csv_path = os.path.join(output_dir, "preference_annotations.csv")
        df.to_csv(csv_path, index=False)
